import { StructuredSymptomSummary, EmergencyInfo, DoctorProfile, MedicalDepartment } from '../types/anna';

export type ToolHandler = {
  onNavigate?: (page: 'home' | 'kiosk' | 'doctor' | 'admin' | 'demo') => void;
  onSelectDoctor?: (doctor: DoctorProfile | { name: string; department: string }) => void;
  onSelectDepartment?: (dept: string) => void;
  onOpenAppointment?: (dept?: string, reason?: string) => void;
  onEmergencyAlert?: (emergency: EmergencyInfo) => void;
  onSymptomSummary?: (summary: StructuredSymptomSummary) => void;
};

export class ToolManager {
  private handlers: ToolHandler = {};

  constructor(handlers: ToolHandler = {}) {
    this.handlers = handlers;
  }

  public setHandlers(handlers: ToolHandler) {
    this.handlers = { ...this.handlers, ...handlers };
  }

  public handleToolCall(name: string, args: Record<string, any>, result: Record<string, any>): void {
    console.log(`[ToolManager] Handling tool "${name}"`, { args, result });

    switch (name) {
      case 'openWebsite': {
        const page = (args.page || result.page || 'home').toLowerCase();
        if (['home', 'kiosk', 'doctor', 'admin', 'demo'].includes(page)) {
          this.handlers.onNavigate?.(page as any);
        }
        break;
      }

      case 'openDoctor': {
        const doctorData = result.doctor || {
          name: args.doctorName || 'Dr. Vivek Sharma',
          department: args.specialty || 'General Medicine',
        };
        this.handlers.onSelectDoctor?.(doctorData);
        break;
      }

      case 'openDepartment': {
        const dept = args.department || result.department || 'General Medicine';
        this.handlers.onSelectDepartment?.(dept);
        break;
      }

      case 'openAppointment': {
        this.handlers.onOpenAppointment?.(args.department, args.reason);
        break;
      }

      case 'showEmergencyInformation': {
        const emergencyInfo: EmergencyInfo = {
          isEmergency: true,
          reason: args.emergencyReason || result.reason || 'Potential acute medical emergency detected',
          recommendedAction:
            args.recommendedAction ||
            result.recommendedAction ||
            'Immediate emergency medical attention required. Call 112 / 108 or report to nearest Emergency Room.',
          emergencyContacts: [
            { label: 'National Emergency', number: '112' },
            { label: 'Ambulance Helpline', number: '108' },
            { label: 'Hospital Emergency Unit', number: '+91 11 2999 1234' },
          ],
          timestamp: new Date().toISOString(),
        };
        this.handlers.onEmergencyAlert?.(emergencyInfo);
        break;
      }

      case 'createSymptomSummary': {
        const summary: StructuredSymptomSummary = {
          id: result.summaryId || `SUM-${Date.now().toString().slice(-5)}`,
          timestamp: new Date().toISOString(),
          patientReported: {
            chiefComplaint: args.chiefComplaint || 'Reported symptom',
            onsetDuration: args.onsetDuration || 'Recent onset',
            location: args.location || 'General',
            severity: String(args.severity || 'Moderate'),
            associatedSymptoms: Array.isArray(args.associatedSymptoms) ? args.associatedSymptoms : [],
            additionalNotes: args.patientReportedNotes || '',
          },
          clinicalStructuring: {
            triageCategory:
              String(args.severity).toLowerCase().includes('severe') || Number(args.severity) >= 8
                ? 'URGENT'
                : 'ROUTINE',
            recommendedDepartment: args.recommendedDepartment || result.recommendedDepartment || 'General Medicine',
            suggestedDoctors: ['Dr. Vivek Sharma, MD', 'Dr. Ananya Mukherjee, MD(Ayu)'],
            suggestedQuestionsForDoctor: [
              'What diagnostic tests (ECG, ultrasound, or blood work) should be ordered first?',
              'Are there warning signs I should watch for at home?',
            ],
            disclaimer:
              'Generated by AI Voice Assistant Anna for clinical pre-consultation triage. Final assessment will be completed by the attending doctor.',
          },
        };
        this.handlers.onSymptomSummary?.(summary);
        break;
      }

      default:
        console.log(`[ToolManager] Unhandled tool "${name}"`);
    }
  }
}
